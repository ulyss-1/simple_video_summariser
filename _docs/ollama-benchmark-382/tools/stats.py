"""Final tables from raw/ + logs/sidecar.jsonl -> out/tables.md and out/runs.json (no model calls)."""
import json
from pathlib import Path
from statistics import mean

B = Path("/tmp/claude-1000/-home-hamlet-proj-simple-video-summariser/e3a54feb-0d54-45c2-8062-6e3778da6fb2/scratchpad/b382")
RAW = B / "raw"
man = {m["video_id"]: m for m in json.loads((B / "manifest.json").read_text())}
side = [json.loads(line) for line in (B / "logs/sidecar.jsonl").read_text().splitlines() if line.strip()]


def calls_of(r):
    p = RAW / f"{r['label']}__{r['video_id']}__{r['model'].replace(':', '_')}.calls.jsonl"
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def rate(cs, cnt, dur):
    n = sum(c.get(cnt) or 0 for c in cs)
    d = sum(c.get(dur) or 0 for c in cs) / 1e9
    return n / d if d else None


def f(x, nd=1):
    return "-" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


runs = []
for p in sorted(RAW.glob("*.result.json")):
    r = json.loads(p.read_text())
    cs = calls_of(r)
    ok = [c for c in cs if c.get("status") == 200]
    chunk = [c for c in ok if c["kind"] == "chunk"]
    sw = [s for s in side if r["started_epoch"] <= s["t"] <= r["ended_epoch"]]
    secs = [s for s in sw]
    dur_min = r["wall_sec"] / 60
    video = man[r["video_id"]]
    row = {
        "label": r["label"], "video": r["video_id"], "model": r["model"], "num_ctx": r["settings"]["OLLAMA_NUM_CTX"],
        "status": r["status"], "wall_s": r["wall_sec"], "calls": len(cs), "ok_calls": len(ok),
        "by_kind": {k: sum(1 for c in cs if c["kind"] == k) for k in ("roster", "chunk", "reduce", "repair")},
        "prefill_tps": rate(ok, "prompt_eval_count", "prompt_eval_duration"),
        "gen_tps": rate(ok, "eval_count", "eval_duration"),
        "load_s": (ok[0].get("load_duration") or 0) / 1e9 if ok else None,
        "prompt_tokens": [c.get("prompt_eval_count") for c in ok], "out_tokens": [c.get("eval_count") for c in ok],
        "chunk_out_tokens": [c.get("eval_count") for c in chunk],
        "length_calls": sum(1 for c in ok if c.get("done_reason") == "length"),
        "chunk_over_2048": sum(1 for c in chunk if (c.get("eval_count") or 0) > 2048),
        "cause": (r.get("outcome_text") or r.get("reason") or "")[:140],
        "last_call_error": next((c.get("error") for c in reversed(cs) if c.get("error")), None),
        "peak_used_gb": r["mem"]["peak_used_kb"] / 1048576, "peak_swap_gb": r["mem"]["peak_swap_kb"] / 1048576,
        "peak_runner_gb": r["mem"]["peak_runner_kb"] / 1048576, "min_avail_gb": r["mem"]["min_avail_kb"] / 1048576,
        "sec_per_video_min": r["wall_sec"] / (video["duration_sec"] / 60) if r["status"] == "ok" else None,
        "sidecar_samples": len(secs),
        "max_psi_full10": max((s["psi_full10"] for s in secs), default=None),
        "swapin_mb": sum(s["pswpin_pages"] for s in secs) * 4096 / 1e6 if secs else None,
        "swapout_mb": sum(s["pswpout_pages"] for s in secs) * 4096 / 1e6 if secs else None,
        "loadavg_before": r["pre"]["loadavg"],
        "unsuspected_cache_hits": None,
    }
    # prompt-cache flag: below 50% of estimate_tokens(request)/1.5 (first call of a run is never flagged)
    sus = 0
    for i, c in enumerate(ok):
        if i and c.get("prompt_eval_count") is not None and c["prompt_eval_count"] < 0.5 * c["request_est_tokens"] / 1.5:
            sus += 1
    row["suspected_cache_hits"] = sus
    row["unsuspected_cache_hits"] = None
    runs.append(row)
(B / "out").mkdir(exist_ok=True)
(B / "out/runs.json").write_text(json.dumps(runs, indent=1))

HDR = ("| video | est tok | model | status | wall s | s per video-min | calls (r/c/red/rep) | prefill tok/s | gen tok/s | load s "
       "| prompt tok/call | out tok/call | length | peak used GB | peak swap GB | runner GB | min avail GB | max PSI full10 | swap in/out MB |\n"
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")


def line(r):
    k = r["by_kind"]
    return (f"| {r['video']} | {man[r['video']]['est_tokens']} | {r['model']} | {r['status']} | {r['wall_s']:.0f} | {f(r['sec_per_video_min'])} "
            f"| {k['roster']}/{k['chunk']}/{k['reduce']}/{k['repair']} | {f(r['prefill_tps'])} | {f(r['gen_tps'])} | {f(r['load_s'])} "
            f"| {r['prompt_tokens']} | {r['out_tokens']} | {r['length_calls']} | {r['peak_used_gb']:.1f} | {r['peak_swap_gb']:.1f} "
            f"| {r['peak_runner_gb']:.1f} | {r['min_avail_gb']:.1f} | {f(r['max_psi_full10'], 2)} "
            f"| {f(r['swapin_mb'], 0)}/{f(r['swapout_mb'], 0)} |\n")


def order(rs):
    return sorted(rs, key=lambda r: (man[r["video"]]["est_tokens"], r["model"]))


out = ["# #382 run tables (generated by tools/stats.py)\n\n",
       "Rates: sum of counts over sum of durations over the run's successful HTTP calls. 'length' = calls with done_reason=length. "
       "PSI and swap columns come from the sidecar sampler (started 03:30 IST): '-' for runs before it started. "
       "Runner RSS is 0 for the first run (bIvyxp-FAGU gemma; filter fixed afterwards).\n\n"]
for title, sel in (("Main protocol (num_ctx 8192, cap 45 min/run)", lambda r: r["label"] == "main"),
                   ("Labelled experiment ctx16k (num_ctx 16384, cap 75 min/run)", lambda r: r["label"] == "ctx16k"),
                   ("Repeats (label rep1, gemma4:e4b on qovnfjVd8cs, 8192)", lambda r: r["label"].startswith("rep"))):
    out.append(f"## {title}\n\n" + HDR + "".join(line(r) for r in order([r for r in runs if sel(r)])) + "\n")
out.append("Failures (main and labelled), with cause:\n\n")
for r in order(runs):
    if r["status"] != "ok":
        out.append(f"- {r['label']} {r['video']} {r['model']}: {r['status']} after {r['wall_s']:.0f} s; {r['cause'] or 'no outcome text (run cap)'}; last call error {r['last_call_error']}\n")
out.append("\nCancelled: label `rerun` (qwen3.5:4b on qovnfjVd8cs, 8192) started 08:03:42, cancelled by the orchestrator 08:04:40, no result.\n\n")

out.append("## Per model and num_ctx: chunk-call output tokens and runaway generation (successful calls only)\n\n"
           "| label | model | num_ctx | chunk calls | mean out tok | max out tok | chunk calls > 2048 out | calls with done_reason=length |\n|---|---|---|---|---|---|---|---|\n")
for lab in ("main", "ctx16k", "rep1"):
    for m in ("qwen3.5:4b", "gemma4:e4b"):
        rs = [r for r in runs if r["label"] == lab and r["model"] == m]
        if not rs:
            continue
        co = [t for r in rs for t in r["chunk_out_tokens"] if t is not None]
        out.append(f"| {lab} | {m} | {rs[0]['num_ctx']} | {len(co)} | {f(mean(co) if co else None)} | {max(co) if co else '-'} "
                   f"| {sum(r['chunk_over_2048'] for r in rs)} | {sum(r['length_calls'] for r in rs)} |\n")
out.append("\nNote: a call that ends with done_reason=length raises the adapter's context error and the run fails; "
           "the failed call's tokens are in the failure line (qwen EfGtEDJyRvk 5593+2599, gemma eEE3S-MvzEs 6029+2163 at 8192).\n\n")

out.append("## Main protocol, models side by side over the videos both completed (ok)\n\n")
HDR2 = ("| metric | qwen3.5:4b mean | qwen worst | gemma4:e4b mean | gemma worst |\n|---|---|---|---|---|\n")
both = [v for v in man if all(any(r for r in runs if r["label"] == "main" and r["video"] == v and r["model"] == m and r["status"] == "ok") for m in ("qwen3.5:4b", "gemma4:e4b"))]
out.append(f"Videos with both ok: {both}\n\n" + HDR2)
for name, key, worst in (("prefill tok/s", "prefill_tps", min), ("generation tok/s", "gen_tps", min), ("load s", "load_s", max),
                         ("wall s", "wall_s", max), ("s per video minute", "sec_per_video_min", max)):
    cells = []
    for m in ("qwen3.5:4b", "gemma4:e4b"):
        vals = [r[key] for r in runs if r["label"] == "main" and r["model"] == m and r["status"] == "ok" and r["video"] in both and r[key] is not None]
        cells += [f(mean(vals)) if vals else "-", f(worst(vals)) if vals else "-"]
    out.append(f"| {name} | " + " | ".join(cells) + " |\n")
(B / "out/tables.md").write_text("".join(out))
print("".join(out)[:200])
